// Writes src/lib/trees/speciesTable.ts: for every species in Portland's street
// tree inventory, its genus, its family, and whether the city counts it as
// native and as a nuisance. The app reads only that checked-in table.
//
//   node scripts/street-tree-species.mjs
//
// Where it comes from: the City of Portland's own street tree inventory
// (Parks & Recreation Urban Forestry, 2022–2024), the richer "STI v2" layer
// the city publishes on its ArcGIS Online organisation:
//
//   https://services.arcgis.com/quVN97tn06YNGj9s/arcgis/rest/services/STI_v2_FINAL_dataset_public/FeatureServer/316
//
// That host is an Esri one, which the app itself must never call (a standing
// rule of the project: their terms need an account). This script runs by hand,
// offline from the app, and asks only for counts grouped by species, genus,
// family, NATIVE and NUISANCE: no addresses, no individual trees.
//
// The open-data layer the app reads at run time (portlandmaps.com, layer 1415)
// names a species "Acer platanoides - Norway maple"; the part before " - " is
// the scientific name this table is keyed by (lower case).

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const SERVICE =
  "https://services.arcgis.com/quVN97tn06YNGj9s/arcgis/rest/services/STI_v2_FINAL_dataset_public/FeatureServer/316/query";
const OUT = fileURLToPath(new URL("../src/lib/trees/speciesTable.ts", import.meta.url));

const fields = ["SPECIES_SCIENTIFIC_NAME", "GENUS_SCIENTIFIC_NAME", "FAMILY", "NATIVE", "NUISANCE"];

async function page(offset) {
  const params = new URLSearchParams({
    where: "1=1",
    outStatistics: JSON.stringify([
      { statisticType: "count", onStatisticField: "OBJECTID", outStatisticFieldName: "n" },
    ]),
    groupByFieldsForStatistics: fields.join(","),
    orderByFields: fields.join(","),
    resultOffset: String(offset),
    resultRecordCount: "1000",
    f: "json",
  });
  const response = await fetch(`${SERVICE}?${params}`);
  if (!response.ok) throw new Error(`HTTP ${response.status}`);
  const answer = await response.json();
  if (answer.error) throw new Error(JSON.stringify(answer.error));
  return answer;
}

const rows = [];
for (let offset = 0; ;) {
  const answer = await page(offset);
  const features = answer.features ?? [];
  rows.push(...features.map((feature) => feature.attributes));
  if (!answer.exceededTransferLimit || features.length === 0) break;
  offset += features.length;
}

const clean = (value) => (typeof value === "string" ? value.trim() : "");
const yes = (value) => clean(value).toLowerCase() === "yes";

/** scientific name (lower case) → the row with the most trees, should a name appear twice. */
const species = new Map();
/** genus → family → trees, to pick each genus's family by majority. */
const genusFamilies = new Map();
for (const row of rows) {
  const name = clean(row.SPECIES_SCIENTIFIC_NAME).toLowerCase();
  const genus =
    clean(row.GENUS_SCIENTIFIC_NAME) || clean(row.SPECIES_SCIENTIFIC_NAME).split(" ")[0];
  const family = clean(row.FAMILY);
  if (genus && family) {
    const counts = genusFamilies.get(genus) ?? new Map();
    counts.set(family, (counts.get(family) ?? 0) + row.n);
    genusFamilies.set(genus, counts);
  }
  if (!name) continue;
  const known = species.get(name);
  if (known && known.n >= row.n) continue;
  species.set(name, {
    n: row.n,
    genus,
    family,
    native: yes(row.NATIVE),
    nuisance: yes(row.NUISANCE),
  });
}

const familyOf = new Map(
  [...genusFamilies].map(([genus, counts]) => [
    genus,
    [...counts].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))[0][0],
  ]),
);

const speciesLines = [...species]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(
    ([name, row]) => `  ${JSON.stringify(name)}: ${(row.native ? 1 : 0) + (row.nuisance ? 2 : 0)},`,
  );
const familyLines = [...familyOf]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([genus, family]) => `  ${JSON.stringify(genus.toLowerCase())}: ${JSON.stringify(family)},`);

const total = rows.reduce((sum, row) => sum + row.n, 0);
const source = `/**
 * GENERATED by \`node scripts/street-tree-species.mjs\` — do not edit by hand.
 *
 * From the City of Portland's street tree inventory (Parks & Recreation
 * Urban Forestry, 2022–2024; ${total.toLocaleString("en-US")} trees, ${species.size} species), as
 * counts grouped by species: see the script for where it was read and why
 * the app never reads that host itself.
 */

/**
 * Scientific name (lower case) → flags: 1 = native to the Portland area,
 * 2 = on the city's nuisance list, 3 = both, 0 = neither.
 */
export const SPECIES_FLAGS: Readonly<Record<string, number>> = {
${speciesLines.join("\n")}
};

/** Genus (lower case) → botanical family. */
export const GENUS_FAMILY: Readonly<Record<string, string>> = {
${familyLines.join("\n")}
};
`;
writeFileSync(OUT, source);
console.error(`${species.size} species, ${familyOf.size} genera → ${OUT}`);
